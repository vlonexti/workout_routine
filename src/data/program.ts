export type WednesdayVariantResolved = 'core' | 'legs'

/**
 * Wednesday runs a two-week rotation: odd training weeks are the short core
 * session, even weeks are legs. Derived from the lifter's training week,
 * which already lives in Postgres, so the rotation survives a refresh or a
 * move to another device without needing its own state.
 */
export function wednesdayForWeek(week: number): WednesdayVariantResolved {
  return week % 2 === 1 ? 'core' : 'legs'
}

export function wednesdayDayKey(variant: WednesdayVariantResolved): string {
  return variant === 'legs' ? 'wed-legs' : 'wed-core'
}
